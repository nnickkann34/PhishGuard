@app.get("/api/health", response_model=HealthResponse, tags=["System"],
         summary="Check that the API and model are ready")
async def health(request: Request):
    """Returns the loaded model's name and hash, and which defences are switched on."""
    m = request.app.state.model
    return HealthResponse(status="ok", model=m.name, model_sha256=m.sha256,
                          dos_protection=settings.dos_protection,
                          homoglyph_normalisation=settings.normalise_homoglyphs)


@app.post("/api/check", response_model=CheckResult, tags=["Checks"],
          summary="Check one web address", responses={**COMMON_ERRORS, **BUSY_ERROR,
                                                     400: {"model": ErrorResponse, "description": "Bad X-Session-ID header."}})
async def check_url(
    body: CheckRequest,
    request: Request,
    session_id: Annotated[str | None, Depends(session_id_header)],
    db=Depends(get_db),
):
    """
    Returns the verdict (phishing or legitimate), the model's confidence, the parts of the
    address that look suspicious, and the features that drove the decision.

    Example request: `{"url": "http://paypal.com.secure-login.xyz/verify"}`
    """
    model: PhishingModel = request.app.state.model
    pred: Prediction = await request.app.state.guard.run(_predict_one, model, body.url)
    record_id = None
    when = datetime.now(timezone.utc)
    if session_id:
        row = store.add_check(db, session_id, pred.url, pred.verdict, pred.malicious_probability,
                              pred.confidence, pred.warnings)
        record_id, when = row.id, row.created_at
    return _to_result(pred, record_id, when)


@app.post("/api/check/batch", response_model=BatchCheckResult, tags=["Checks"],
          summary="Check several web addresses at once", responses={**COMMON_ERRORS, **BUSY_ERROR})
async def check_batch(body: BatchCheckRequest, request: Request):
    """
    Checks up to the configured number of addresses (default 50), for example every link
    found in one email. Results are not saved to history.

    Example request: `{"urls": ["https://www.swinburne.edu.au", "bit.ly/3xYz-login"]}`
    """
    model: PhishingModel = request.app.state.model

    def run_all(urls: list[str]) -> list[Prediction]:
        return [_predict_one(model, u) for u in urls]

    preds = await request.app.state.guard.run(run_all, body.urls)
    now = datetime.now(timezone.utc)
    results = [_to_result(p, None, now, top=5) for p in preds]
    phishing = sum(r.verdict == "phishing" for r in results)
    return BatchCheckResult(results=results, phishing_count=phishing, legitimate_count=len(results) - phishing)


@app.get("/api/history", response_model=HistoryResponse, tags=["History"],
         summary="List this session's past checks",
         responses={400: {"model": ErrorResponse, "description": "Missing or bad X-Session-ID header."}, **COMMON_ERRORS})
async def history(
    session_id: Annotated[str, Depends(required_session)],
    db=Depends(get_db),
    search: Annotated[str | None, Query(max_length=200, description="Only checks whose address contains this text.")] = None,
    limit: Annotated[int, Query(ge=1, le=500, description="Most items to return.")] = 100,
):
    """Returns this browser session's checks, newest first. Other sessions' checks are never included."""
    finder = store.search_history_insecure if settings.insecure_sql_demo else store.search_history
    rows = finder(db, session_id, search, min(limit, settings.history_page_size))
    items = [HistoryItem(id=r.id, url=r.url, verdict=r.verdict, confidence=r.confidence,
                         malicious_probability=r.malicious_probability,
                         warnings=[w for w in r.warnings.split("\n") if w], checked_at=r.created_at)
             for r in rows]
    return HistoryResponse(items=items, count=len(items))


@app.delete("/api/history", response_model=ClearResponse, tags=["History"],
            summary="Delete this session's history",
            responses={400: {"model": ErrorResponse, "description": "Missing or bad X-Session-ID header."}})
async def clear(session_id: Annotated[str, Depends(required_session)], db=Depends(get_db)):
    """Permanently deletes every check saved for this browser session."""
    return ClearResponse(deleted=store.clear_history(db, session_id))


@app.get("/api/stats", response_model=StatsResponse, tags=["History"],
         summary="Summary of this session's checks",
         responses={400: {"model": ErrorResponse, "description": "Missing or bad X-Session-ID header."}})
async def stats(session_id: Annotated[str, Depends(required_session)], db=Depends(get_db)):
    """Counts of phishing and legitimate verdicts and the average confidence for each."""
    return StatsResponse(**store.session_stats(db, session_id))
