settings = get_settings()
log = logging.getLogger("phishguard")
logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s %(message)s")

SESSION_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$")


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Loaded once, here, when the server starts - never per request.
    app.state.model = PhishingModel(settings.model_path, settings.metadata_path, settings.model_sha256_path)
    app.state.guard = InferenceGuard(
        settings.inference_workers, settings.inference_queue,
        settings.inference_timeout_seconds, enabled=settings.dos_protection,
    )
    app.state.sessions = store.make_session_factory(settings.database_url)
    log.info("Model %s loaded (sha256 %s...). DoS protection=%s, homoglyph normalisation=%s, insecure SQL demo=%s",
             app.state.model.name, app.state.model.sha256[:12], settings.dos_protection,
             settings.normalise_homoglyphs, settings.insecure_sql_demo)
    if settings.insecure_sql_demo:
        log.warning("INSECURE SQL DEMO MODE IS ON - history search is injectable. Demo use only.")
    yield
    app.state.guard.shutdown()


COMMON_ERRORS = {
    413: {"model": ErrorResponse, "description": "Request body too large."},
    422: {"model": ErrorResponse, "description": "The input failed validation."},
    500: {"model": ErrorResponse, "description": "Unexpected server error (no internal details are returned)."},
}
BUSY_ERROR = {503: {"model": ErrorResponse, "description": "Server busy or the check timed out; retry after the Retry-After header."}}

app = FastAPI(
    title="PhishGuard API",
    version="1.0.0",
    description=(
        "Checks whether a web address looks like phishing, using a machine-learning model "
        "trained on 859,127 labelled URLs. Addresses are analysed as text only: PhishGuard "
        "never visits, fetches or resolves them.\n\n"
        "Send an `X-Session-ID` header (a random UUID v4 generated by the browser) to keep a "
        "private history of checks for that browser session."
    ),
    lifespan=lifespan,
)

async def request_context(request: Request, call_next):
    """Tags each request with an id, logs it, and turns any unexpected crash into a clean 500."""
    request.state.request_id = uuid.uuid4().hex[:12]
    start = time.perf_counter()
    try:
        response = await call_next(request)
    except Exception:
        log.exception("Unhandled error [%s]", request.state.request_id)
        response = JSONResponse(status_code=500, content=error_payload(
            "internal_error", "Something went wrong on our side. Please try again.",
            request.state.request_id))
    response.headers["X-Request-ID"] = request.state.request_id
    log.info("%s %s -> %s in %.1f ms [%s]", request.method, request.url.path,
             response.status_code, (time.perf_counter() - start) * 1000, request.state.request_id)
    return response


# Middleware runs outermost-first in the reverse order it is added here:
# CORS -> request context -> body size limit -> security headers -> routes.
# CORS is outermost so even 413, 500 and 503 responses reach the browser.
app.add_middleware(SecurityHeadersMiddleware)
app.add_middleware(BodySizeLimitMiddleware, max_bytes=settings.max_body_bytes)
app.add_middleware(BaseHTTPMiddleware, dispatch=request_context)
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.allowed_origins,
    allow_methods=["GET", "POST", "DELETE"],
    allow_headers=["Content-Type", "X-Session-ID"],
    expose_headers=["X-Request-ID", "Retry-After"],
    max_age=600,
)


# --------------------------------------------------------------------------
# Errors: every error, expected or not, uses the same JSON shape.
# --------------------------------------------------------------------------

def _rid(request: Request) -> str:
    return getattr(request.state, "request_id", "unknown")


@app.exception_handler(RequestValidationError)
async def on_validation_error(request: Request, exc: RequestValidationError):
    details = []
    for err in exc.errors():
        field = ".".join(str(p) for p in err.get("loc", []) if p not in ("body", "query", "header"))
        problem = err.get("msg", "Invalid value").removeprefix("Value error, ")
        details.append({"field": field or "request", "problem": problem})
    return JSONResponse(status_code=422, content=error_payload(
        "validation_error", "The request is not valid.", _rid(request), details))


@app.exception_handler(StarletteHTTPException)
async def on_http_error(request: Request, exc: StarletteHTTPException):
    codes = {400: "bad_request", 404: "not_found", 405: "method_not_allowed",
             413: "payload_too_large", 415: "unsupported_media_type"}
    message = exc.detail if isinstance(exc.detail, str) else "Request failed."
    if exc.status_code == 404 and message == "Not Found":
        message = "There is no endpoint at this address."
    return JSONResponse(status_code=exc.status_code, headers=getattr(exc, "headers", None),
                        content=error_payload(codes.get(exc.status_code, "http_error"), message, _rid(request)))


@app.exception_handler(ServerBusyError)
async def on_busy(request: Request, exc: ServerBusyError):
    return JSONResponse(status_code=503, headers={"Retry-After": str(exc.retry_after)},
                        content=error_payload("server_busy", exc.reason, _rid(request)))


@app.exception_handler(Exception)
async def on_unexpected(request: Request, exc: Exception):
    # Log the full error for us; return nothing internal to the client.
    log.exception("Unhandled error [%s]", _rid(request))
    return JSONResponse(status_code=500, content=error_payload(
        "internal_error", "Something went wrong on our side. Please try again.", _rid(request)))


