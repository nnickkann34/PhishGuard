def get_db(request: Request):
    with request.app.state.sessions() as session:
        yield session


def session_id_header(
    x_session_id: Annotated[str | None, Header(description="Random UUID v4 identifying this browser session.")] = None,
) -> str | None:
    if x_session_id is None:
        return None
    if not SESSION_RE.match(x_session_id.lower()):
        raise HTTPException(status_code=400, detail="X-Session-ID must be a UUID v4.")
    return x_session_id.lower()


def required_session(session_id: Annotated[str | None, Depends(session_id_header)]) -> str:
    if session_id is None:
        raise HTTPException(status_code=400, detail="The X-Session-ID header is required for history.")
    return session_id


def _to_result(pred: Prediction, record_id: int | None, when: datetime, top: int = 8) -> CheckResult:
    return CheckResult(
        id=record_id, url=pred.url, verdict=pred.verdict, confidence=pred.confidence,
        malicious_probability=pred.malicious_probability, warnings=pred.warnings,
        lookalike_characters=bool(pred.normalisation and pred.normalisation.suspicious),
        contributions=pred.contributions[:top], checked_at=when,
    )


def _predict_one(model: PhishingModel, url: str) -> Prediction:
    try:
        return model.predict(url, normalise=settings.normalise_homoglyphs)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=f"Could not read that address: {exc}") from None


